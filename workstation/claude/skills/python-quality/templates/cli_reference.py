"""
Renders the CLI reference from the parser itself.

Hand-copied `--help` output drifts the moment a flag changes — this project has already shipped a
stale command list once. Generating it means the reference cannot disagree with the program, and
`make check` fails when the committed copy is out of date.

    python -m your_package.reference > docs/cli.md
"""

import argparse

from confluence_sync.cli import parser


def render(command: argparse.ArgumentParser, name: str, level: int = 2) -> list[str]:
    """The command and every subcommand below it, as Markdown sections."""

    lines = [f"{'#' * level} {name}", "", "```", command.format_help().rstrip(), "```", ""]
    for action in command._actions:
        if isinstance(action, argparse._SubParsersAction):
            for subcommand, subparser in sorted(action.choices.items()):
                lines += render(subparser, f"{name} {subcommand}", level + 1)
    return lines


def main() -> int:
    """Writes the whole reference to stdout."""

    print("# CLI reference\n")
    print("<!-- Generated by `make docs`. Do not edit: your changes will be overwritten. -->\n")
    print("\n".join(render(parser(), "your-command")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
